// Share one Mongo client everywhere (better-auth + API routes) so we don't 
// blow past connection limits or cause connection storms.

import { MongoClient } from "mongodb";

const mongoUri = process.env.MONGODB_URI;
if (!mongoUri) {
  throw new Error("MONGODB_URI environment variable is missing!");
}

let cachedClient = null;
let cachedDb = null;
let indexesReadyPromise = null;

export function getMongoClient() {
  if (!cachedClient) {
    cachedClient = new MongoClient(mongoUri, {
      maxPoolSize: 10,
      minPoolSize: 1, // Keep a connection warm so cold starts don't feel sluggish
      serverSelectionTimeoutMS: 5000,
      socketTimeoutMS: 45000,
    });
    console.log("💾 MongoDB Atlas: Shared connection pool created.");
  }
  return cachedClient;
}

// Returns a connected database instance. The first time this is called, it will also ensure that the indexes we need exist.
export async function getDatabase() {
  if (cachedDb) return cachedDb;

  const client = getMongoClient();
  await client.connect(); // Safe to call even if we're already connected

  cachedDb = client.db();

  // Create indexes for the collections we use. This is safe to call multiple times, and will only create the indexes once. We do this here so that the first request to the API will ensure the indexes exist before any other requests are processed.
  if (!indexesReadyPromise) {
    indexesReadyPromise = Promise.all([
      cachedDb.collection("cards").createIndex({ userId: 1, createdAt: -1 }),
      cachedDb.collection("cards").createIndex({ userId: 1, isBookmarked: 1 }),
      cachedDb.collection("cards").createIndex({ userId: 1, type: 1 }),
      // Supports sorting a user's cards by their manual drag-and-drop order
      cachedDb.collection("cards").createIndex({ userId: 1, order: 1 }),

      // These two indexes are used to prevent duplicate cards/snippets from being created when the same request is sent multiple times (e.g. double-clicking a button, or a network retry). The first index is for cards/snippets that have a clientRequestId (generated by the frontend), and the second index is for cards/snippets that have a contentHash (generated by the backend).
      cachedDb.collection("cards").createIndex(
        { userId: 1, clientRequestId: 1 },
        { unique: true, sparse: true }
      ),
      
      cachedDb.collection("cards").createIndex(
        { userId: 1, contentHash: 1 },
        { unique: true, partialFilterExpression: { contentHash: { $exists: true } } }
      ),
      cachedDb.collection("snippets").createIndex({ userId: 1, createdAt: -1 }),
      cachedDb.collection("snippets").createIndex({ userId: 1, bookmarked: 1 }),
      // Supports sorting standalone snippets by their manual drag-and-drop order
      cachedDb.collection("snippets").createIndex({ userId: 1, order: 1 }),
      cachedDb.collection("snippets").createIndex(
        { userId: 1, clientRequestId: 1 },
        { unique: true, sparse: true }
      ),
      cachedDb.collection("snippets").createIndex(
        { userId: 1, contentHash: 1 },
        { unique: true, partialFilterExpression: { contentHash: { $exists: true } } }
      ),
      cachedDb.collection("categories").createIndex({ userId: 1, createdAt: -1 }),
      cachedDb.collection("categories").createIndex({ userId: 1, nameLower: 1 }, { unique: true }),
    ]).catch((idxErr) => {
      console.warn("Index initialization notice:", idxErr.message);
    });
  }
  await indexesReadyPromise;

  return cachedDb;
}